/**
 * Every internal link and anchor on the BUILT docs site resolves.
 *
 * Built HTML, not markdown source, and that is the point: four of the site's
 * reference pages are GENERATED and git-ignored, so a checker reading the sources
 * cannot see them — it would either skip the generated pages or report every link
 * into them as broken. The build is also where a rename actually lands.
 *
 * Run after `pnpm --filter @aparte-workspace/docs build` (CI does exactly that).
 */
import { readFileSync, readdirSync, statSync, existsSync } from 'node:fs';
import { join, relative, sep } from 'node:path';

const DIST = 'apps/docs/dist';

if (!existsSync(DIST)) {
    console.error(`\n[doc-links] ${DIST} not found — build the docs first:\n  pnpm --filter @aparte-workspace/docs build\n`);
    process.exit(1);
}

function* walk(dir) {
    for (const name of readdirSync(dir)) {
        const path = join(dir, name);
        if (statSync(path).isDirectory()) yield* walk(path);
        else if (path.endsWith('.html')) yield path;
    }
}

const pages = [...walk(DIST)];
/** url path (with trailing slash) -> the set of ids on that page */
const idsByRoute = new Map();

const routeOf = (file) => {
    const rel = relative(DIST, file).split(sep).join('/');
    if (rel === 'index.html') return '/';
    if (rel.endsWith('/index.html')) return `/${rel.slice(0, -'/index.html'.length)}/`;
    return `/${rel.replace(/\.html$/, '')}`;
};

for (const file of pages) {
    const html = readFileSync(file, 'utf8');
    const ids = new Set();
    for (const m of html.matchAll(/\sid="([^"]+)"/g)) ids.add(m[1]);
    for (const m of html.matchAll(/\sname="([^"]+)"/g)) ids.add(m[1]);
    idsByRoute.set(routeOf(file), ids);
}

const broken = [];
let checked = 0;
/** Every route some page links TO — the other half of "the links resolve". */
const linkedTo = new Set();

for (const file of pages) {
    const from = routeOf(file);
    const html = readFileSync(file, 'utf8');
    for (const m of html.matchAll(/<a\b[^>]*\shref="([^"]+)"/g)) {
        const href = m[1];
        // External, in-page-only, and non-navigational hrefs are out of scope.
        if (/^(?:[a-z]+:|\/\/)/i.test(href)) continue;
        if (href.startsWith('#')) {
            checked++;
            if (!idsByRoute.get(from)?.has(decodeURIComponent(href.slice(1)))) {
                broken.push(`${from} → ${href} (no such anchor on this page)`);
            }
            continue;
        }
        if (!href.startsWith('/')) continue; // relative asset links: not routes
        checked++;
        const [rawPath, hash] = href.split('#');
        const path = rawPath.endsWith('/') || /\.[a-z0-9]+$/i.test(rawPath) ? rawPath : `${rawPath}/`;
        if (!idsByRoute.has(path)) {
            // Could be a static asset (og image, txt, xml) rather than a page.
            if (existsSync(join(DIST, path.replace(/^\//, '')))) continue;
            broken.push(`${from} → ${href} (no such page)`);
            continue;
        }
        linkedTo.add(path);
        if (hash && !idsByRoute.get(path).has(decodeURIComponent(hash))) {
            broken.push(`${from} → ${href} (page exists, anchor does not)`);
        }
    }
}

if (broken.length) {
    console.error(`\n[doc-links] ${broken.length} broken internal link(s) of ${checked} checked:\n`);
    for (const b of [...new Set(broken)].sort()) console.error(`  ${b}`);
    console.error('');
    process.exit(1);
}

/*
 * ── Reachability ─────────────────────────────────────────────────────────────
 *
 * Everything above proves that every link RESOLVES. It says nothing about whether a page
 * is REACHED, and the cold audit proved the gap by sabotage: an unreferenced page raised
 * the count to 40 pages and passed clean.
 *
 * That is the failure ratified decision #4 records THREE times — a capability that ships
 * documented and unreachable, which is functionally undocumented. The first external
 * consumer built his own bar under the chat rather than find slots that existed, because
 * they were cited in one clause on a page he had read.
 *
 * Starlight's sidebar is autogenerated per DIRECTORY, so a page inside `guides/`,
 * `frameworks/`, `plugins/`, `reference/` or `providers/` is linked from every page and
 * safe. A page in a NEW top-level content directory builds a live route, appears in no
 * sidebar, and is reachable only by typing the URL. Nothing failed.
 *
 * The home page is its own root and links inward rather than being linked to, and the
 * machine-readable endpoints are meant to be fetched, not navigated.
 */
// '/' links inward rather than being linked to; llms*.txt are meant to be FETCHED by a
// model, not navigated; '/404' is served on a miss and by definition nothing links to it.
const REACH_EXEMPT = new Set(['/', '/llms.txt/', '/llms-full.txt/', '/404']);

/*
 * A REDIRECT is not an orphan, and the first run of this pass called two of them one.
 *
 * `astro.config.mjs` keeps `/reference/release-notes` → `/changelog/` because the first
 * release of that page used the old URL, and `/404` is served on a miss rather than
 * navigated to. Astro emits a redirect as a stub whose whole body is a meta refresh, so
 * the shape is detectable and needs no list: nothing SHOULD link to a redirect — that is
 * what makes it a redirect.
 *
 * Detected rather than named, because a name is a list somebody has to maintain and the
 * next redirect would fail the build for being correct.
 */
const isRedirectStub = (file) =>
    /<meta\s+http-equiv="refresh"/i.test(readFileSync(file, 'utf8'));
const redirects = new Set(pages.filter(isRedirectStub).map(routeOf));

const orphans = [...idsByRoute.keys()]
    .filter((route) => !REACH_EXEMPT.has(route) && !redirects.has(route) && !linkedTo.has(route))
    .sort();

if (orphans.length) {
    console.error(`\n[doc-links] ${orphans.length} built page(s) that NOTHING links to:\n`);
    for (const o of orphans) console.error(`  ${o}`);
    console.error(
        '\nEach one builds a live route that no reader can find. Link it from a page that is\n'
        + 'itself reachable, or put it in one of the sidebar directories, or — if it is meant\n'
        + 'to be fetched rather than navigated — add it to REACH_EXEMPT in this script with a\n'
        + 'reason.\n'
        + '\nThis is ratified decision #4: "a capability cited in passing, with no example, is\n'
        + 'functionally invisible". A page nothing links to is the same defect, one level up.\n',
    );
    process.exit(1);
}

/*
 * ── What the site's own CONFIG cites must exist among the built pages (#63) ──
 *
 * The llms.txt preamble and the sidebar name routes in `astro.config.mjs` without
 * rendering an <a> for the link walk above to see: the preamble cited a route among
 * its documentation sets while nothing built its index page, and no check could
 * notice. Collected here: every quoted absolute route ('/why/'), every route cited
 * inside prose strings (', /compare/.'), and every `paths: […]` entry of the llms
 * customSets (plain entries as routes, `dir/**` globs as prefixes that must match at
 * least one built page).
 */
const configSrc = readFileSync('apps/docs/astro.config.mjs', 'utf8');
const citedRoutes = new Set();
const citedPrefixes = new Set();
for (const m of configSrc.matchAll(/'(\/[a-z0-9-]+(?:\/[a-z0-9-]+)*\/)'/g)) citedRoutes.add(m[1]);
for (const m of configSrc.matchAll(/[\s(](\/[a-z0-9-]+\/)[.,\s)]/g)) citedRoutes.add(m[1]);
const pathArrays = [...configSrc.matchAll(/paths:\s*\[([^\]]*)\]/g)];
for (const [, body] of pathArrays) {
    for (const m of body.matchAll(/'([a-z0-9-]+(?:\/[a-z0-9-]+)*?)(\/\*\*)?'/g)) {
        if (m[2]) citedPrefixes.add(`/${m[1]}/`);
        else citedRoutes.add(`/${m[1]}/`);
    }
}
if (pathArrays.length === 0) {
    // A corpus that silently shrinks is the failure worth catching: the llms
    // customSets moved or changed shape, and this pass would be reading nothing.
    console.error('\n[doc-links] FAIL: no `paths: […]` arrays found in astro.config.mjs — the llms customSets moved; update this check rather than letting it go blind.\n');
    process.exit(1);
}
const missingCited = [...citedRoutes].filter((r) => !idsByRoute.has(r) && !redirects.has(r)).sort();
const emptyPrefixes = [...citedPrefixes].filter((p) => ![...idsByRoute.keys()].some((r) => r.startsWith(p))).sort();
if (missingCited.length || emptyPrefixes.length) {
    console.error('\n[doc-links] the site\'s own config cites what the build does not contain:\n');
    for (const r of missingCited) console.error(`  ${r} — cited in astro.config.mjs, no built page`);
    for (const p of emptyPrefixes) console.error(`  ${p}** — a customSets glob that matches nothing`);
    console.error('\nA route named in the llms preamble or the sidebar is a promise to a reader\nthe link walk cannot see. Build the page, or stop citing it.\n');
    process.exit(1);
}

/**
 * A floor on what was actually inspected.
 *
 * Without it this script's happiest output is `OK: 0 links` — which is what a
 * broken selector, a renamed build directory or an Astro output change would
 * produce, and it would read as a pass. `check-attr-escaping` learned the same
 * lesson the hard way and carries the same guard. Measured at ~2860 links across
 * 38 pages; the floor sits well below that so adding or removing a page never
 * trips it, while a collapse cannot hide.
 */
const CHECKED_FLOOR = 1500;
const PAGES_FLOOR = 25;
if (checked < CHECKED_FLOOR || pages.length < PAGES_FLOOR) {
    console.error(
        `\n[doc-links] FAIL: only ${checked} links across ${pages.length} pages `
        + `(floors: ${CHECKED_FLOOR} links, ${PAGES_FLOOR} pages).\n`
        + '  Zero broken links out of almost nothing is not a pass, it is a matcher that\n'
        + '  stopped matching — a renamed dist directory, a changed Astro output shape, or\n'
        + '  a docs build that did not run. Check the build before lowering these.\n',
    );
    process.exit(1);
}

console.log(`[doc-links] OK: ${checked} internal links and anchors across ${pages.length} built pages all resolve, and every page is reachable.`);
